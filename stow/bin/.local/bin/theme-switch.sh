#!/usr/bin/env bash
# Applies a palette from themes/<name>/palette.sh across every app.
# Each app gets a generated colors file that its own config already
# sources/imports, so only colors are ever rewritten — never layout.
#
# Usage: theme-switch.sh <palette-name>
set -euo pipefail

THEMES_DIR="$HOME/Documents/tbe-dots-files/themes"

if [[ $# -ne 1 ]]; then
    echo "Usage: $(basename "$0") <palette>" >&2
    echo "Available: $(ls "$THEMES_DIR" | tr '\n' ' ')" >&2
    exit 1
fi

palette="$1"
palette_file="$THEMES_DIR/$palette/palette.sh"

if [[ ! -f "$palette_file" ]]; then
    echo "Unknown palette: $palette" >&2
    notify-send "Theme" "Unknown palette: $palette" 2>/dev/null || true
    exit 1
fi

# shellcheck source=/dev/null
source "$palette_file"

# --- Hyprland + hyprlock ---------------------------------------------------
cat > "$HOME/.config/hypr/colors.conf" <<EOF
# Generated by theme-switch.sh — edit themes/$palette/palette.sh instead.
\$bg = rgb($BG)
\$bg_alt = rgb($BG_ALT)
\$fg = rgb($FG)
\$fg_dim = rgb($FG_DIM)
\$accent = rgba(${ACCENT}ee)
\$accent_dim = rgba(${ACCENT_DIM}ee)
\$border_inactive = rgba(${BORDER}aa)
EOF

# --- waybar ----------------------------------------------------------------
cat > "$HOME/.config/waybar/colors.css" <<EOF
/* Generated by theme-switch.sh — edit themes/$palette/palette.sh instead. */
@define-color bg #$BG;
@define-color bg_alt #$BG_ALT;
@define-color fg #$FG;
@define-color fg_dim #$FG_DIM;
@define-color accent #$ACCENT;
@define-color accent_dim #$ACCENT_DIM;
EOF

# --- rofi ------------------------------------------------------------------
cat > "$HOME/.config/rofi/colors.rasi" <<EOF
/* Generated by theme-switch.sh — edit themes/$palette/palette.sh instead. */
* {
    bg:      #$BG;
    bg-alt:  #$BG_ALT;
    fg:      #$FG;
    fg-dim:  #$FG_DIM;
    accent:  #$ACCENT;
}
EOF

# --- swaync -----------------------------------------------------------------
cat > "$HOME/.config/swaync/colors.css" <<EOF
/* Generated by theme-switch.sh — edit themes/$palette/palette.sh instead. */
@define-color bg #$BG;
@define-color bg_alt #$BG_ALT;
@define-color fg #$FG;
@define-color fg_dim #$FG_DIM;
@define-color accent #$ACCENT;
@define-color border #$BORDER;
EOF

# --- kitty -----------------------------------------------------------------
cat > "$HOME/.config/kitty/theme.conf" <<EOF
# Generated by theme-switch.sh — edit themes/$palette/palette.sh instead.
foreground #$FG
background #$BG

cursor #$ACCENT
cursor_text_color #$BG

selection_foreground #$BG
selection_background #$ACCENT

color0  #$T_BLACK
color8  #$T_BR_BLACK
color1  #$T_RED
color9  #$T_BR_RED
color2  #$T_GREEN
color10 #$T_BR_GREEN
color3  #$T_YELLOW
color11 #$T_BR_YELLOW
color4  #$T_BLUE
color12 #$T_BR_BLUE
color5  #$T_MAGENTA
color13 #$T_BR_MAGENTA
color6  #$T_CYAN
color14 #$T_BR_CYAN
color7  #$T_WHITE
color15 #$T_BR_WHITE
EOF

# --- cava ------------------------------------------------------------------
# cava has no include, but its config takes `theme = '<name>'`, loaded from
# ~/.config/cava/themes/. So we regenerate that one theme file.
cat > "$HOME/.config/cava/themes/current" <<EOF
# Generated by theme-switch.sh — edit themes/$palette/palette.sh instead.
[color]
background = '#$BG'
foreground = '#$ACCENT'
EOF

# --- GTK -------------------------------------------------------------------
# @define-color alone is not enough: modern Adwaita hardcodes most of its
# colors, so redefining the names leaves apps like Thunar untouched. The
# explicit widget rules below are what actually recolors them.
cat > "$HOME/.config/gtk-3.0/gtk.css" <<EOF
/* Generated by theme-switch.sh — edit themes/$palette/palette.sh instead. */
@define-color theme_bg_color #$BG;
@define-color theme_fg_color #$FG;
@define-color theme_base_color #$BG;
@define-color theme_text_color #$FG;
@define-color theme_selected_bg_color #$ACCENT;
@define-color theme_selected_fg_color #$BG;
@define-color insensitive_fg_color #$FG_DIM;
@define-color borders #$BORDER;

/* Everything below is scoped with window:not(#waybar) on purpose: waybar is
   a GTK3 app too, and a bare \`button\` rule here outranks waybar's own
   style.css, drawing boxes around its workspace dots. Popup windows (menus,
   popovers) are separate toplevels, so they stay unscoped — that is what
   colors the tray menus. */

window:not(#waybar), dialog, window:not(#waybar) .view,
window:not(#waybar) notebook, window:not(#waybar) paned {
    background-color: #$BG;
    color: #$FG;
}

window:not(#waybar) headerbar, window:not(#waybar) .titlebar,
window:not(#waybar) toolbar, window:not(#waybar) actionbar {
    background-color: #$BG_ALT;
    background-image: none;
    color: #$FG;
    border-color: #$BORDER;
}

window:not(#waybar) .sidebar, window:not(#waybar) placessidebar,
window:not(#waybar) placessidebar list, window:not(#waybar) stacksidebar {
    background-color: #$BG_ALT;
    color: #$FG;
}

window:not(#waybar) treeview.view, window:not(#waybar) list,
window:not(#waybar) list row {
    background-color: transparent;
    color: #$FG;
}

window:not(#waybar) treeview.view:selected,
window:not(#waybar) list row:selected,
window:not(#waybar) .view:selected,
window:not(#waybar) placessidebar row:selected {
    background-color: #$ACCENT;
    color: #$BG;
}

window:not(#waybar) entry, window:not(#waybar) spinbutton {
    background-color: #$BG_ALT;
    background-image: none;
    color: #$FG;
    border-color: #$BORDER;
    caret-color: #$ACCENT;
}

window:not(#waybar) button {
    background-color: #$BG_ALT;
    background-image: none;
    color: #$FG;
    border-color: #$BORDER;
    text-shadow: none;
}

window:not(#waybar) button:hover {
    background-color: #$BORDER;
}

window:not(#waybar) button:checked, window:not(#waybar) button:active {
    background-color: #$ACCENT;
    color: #$BG;
}

window:not(#waybar) scrollbar, window:not(#waybar) scrollbar trough {
    background-color: #$BG;
    border: none;
}

window:not(#waybar) scrollbar slider {
    background-color: #$FG_DIM;
}

window:not(#waybar) scrollbar slider:hover {
    background-color: #$ACCENT;
}

window:not(#waybar) separator {
    background-color: #$BORDER;
}

window:not(#waybar) progressbar progress,
window:not(#waybar) levelbar block.filled {
    background-color: #$ACCENT;
}

window:not(#waybar) label.dim-label {
    color: #$FG_DIM;
}

/* Popup toplevels: tray menus, context menus, popovers. */
menu, popover, popover.background, .context-menu {
    background-color: #$BG_ALT;
    color: #$FG;
    border: 1px solid #$BORDER;
}

menu menuitem, .context-menu menuitem {
    color: #$FG;
}

menu menuitem:hover, .context-menu menuitem:hover {
    background-color: #$ACCENT;
    color: #$BG;
}
EOF

cat > "$HOME/.config/gtk-4.0/gtk.css" <<EOF
/* Generated by theme-switch.sh — edit themes/$palette/palette.sh instead. */
@define-color window_bg_color #$BG;
@define-color window_fg_color #$FG;
@define-color view_bg_color #$BG;
@define-color view_fg_color #$FG;
@define-color headerbar_bg_color #$BG_ALT;
@define-color headerbar_fg_color #$FG;
@define-color card_bg_color #$BG_ALT;
@define-color popover_bg_color #$BG_ALT;
@define-color accent_bg_color #$ACCENT;
@define-color accent_fg_color #$BG;
@define-color accent_color #$ACCENT;
EOF

# --- Qt (qt5ct / qt6ct) ----------------------------------------------------
# The color list is positional: one entry per QPalette::ColorRole, in enum
# order. Qt5 stops at PlaceholderText (21 roles), Qt6 adds Accent (22).
# Order verified against /usr/include/qt{,6}/QtGui/qpalette.h.
qt_roles() {
    local text="$1"
    echo -n "#$text, #$BG_ALT, #$BG_ALT, #$BG_ALT, #$BG, #$BORDER,"
    echo -n " #$text, #$ACCENT, #$text, #$BG, #$BG, #000000,"
    echo -n " #$ACCENT, #$BG, #$ACCENT, #$ACCENT_DIM, #$BG_ALT, #$BG,"
    echo -n " #$BG_ALT, #$text, #$FG_DIM"
}

for qt in qt5ct qt6ct; do
    accent_role=""
    [[ "$qt" == "qt6ct" ]] && accent_role=", #$ACCENT"
    cat > "$HOME/.config/$qt/colors/current.conf" <<EOF
# Generated by theme-switch.sh — edit themes/$palette/palette.sh instead.
[ColorScheme]
active_colors=$(qt_roles "$FG")$accent_role
inactive_colors=$(qt_roles "$FG")$accent_role
disabled_colors=$(qt_roles "$FG_DIM")$accent_role
EOF
done

# --- reload running apps ---------------------------------------------------
hyprctl reload >/dev/null 2>&1 || true
pkill -SIGUSR2 waybar 2>/dev/null || true
swaync-client --reload-css >/dev/null 2>&1 || true
# Live-reload every running kitty instance (kitty's own
# reload_conf_in_all_kitties() uses SIGUSR1).
pkill -SIGUSR1 kitty 2>/dev/null || true
# No signal for cava: it has no SIGUSR handler, so sending one would kill it.
# An already-open cava widget keeps its old colors until reopened (SUPER+V
# twice), or press 'c' inside it to reload colors.

# GTK reads ~/.config/gtk-3.0/gtk.css once at startup and never re-reads it,
# so long-lived tray apps we own keep the old palette until restarted —
# that's why nm-applet's menu stayed the previous theme's color.
if pgrep -x nm-applet >/dev/null 2>&1; then
    pkill -x nm-applet 2>/dev/null || true
    sleep 0.2
    setsid nm-applet --indicator >/dev/null 2>&1 &
fi

notify-send "Theme" "Switched to $palette" 2>/dev/null || true
